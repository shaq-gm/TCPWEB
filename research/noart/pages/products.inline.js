    const getFitSlugs = (type) => new Set(
      Array.from(document.querySelectorAll(`[data-product-fit="${type}"] [data-fit-slug]`))
        .map((item) => item.getAttribute('data-fit-slug'))
    );
    const fitMain = getFitSlugs('main');
